# Presets compatible with all codecs (placebo does not exist for vvenc/svtav1)
presets = [
    "ultrafast",
    "superfast",
    "veryfast",
    "faster",
    "fast",
    "medium",
    "slow",
    "slower",
    "veryslow",
]

resolutions = ["240p", "360p", "480p", "720p", "1080p"]
codecs = ["libx264", "libx265", "libsvtav1", "libvvenc"]
#, "libxeve"]

total = len(inputs) * len(presets) * len(resolutions) * len(codecs)
print(f"Total combinaisons : {total}")

# Génération de toutes les combinaisons
for i, (input_file, preset, resolution, codec) in enumerate(
    itertools.product(inputs, presets, resolutions, codecs), start=1
):
    # Extract basename from input_file
    input_basename = os.path.splitext(os.path.basename(input_file))[0]
    final_output_name = f"{input_basename}_{codec}_{resolution}_{preset}.json"
    
    cmd = [
        "./veo",
        "per-title", "analyze",
        "-i", input_file,
        "--resolutions", resolution,
        "--codecs", codec,
        "--preset", preset,
        "--charts", "./charts",
        "-o", "results.json", 
    ]

    print(f"[{i}/{total}] Analysis: {codec} | {preset} | {resolution} ← {input_basename}")

    try:
        # Execution with timeout to avoid ghost processes
        subprocess.run(cmd, check=True, timeout=TIMEOUT_SECONDS)
        
        # 3. Move and rename if the temporary file exists
        if os.path.exists("results.json"):
            shutil.move("results.json", final_output_name)
            print(f"  ✓ Saved: {final_output_name}")
        else:
            print(f"  ⚠ Error: 'results.json' was not generated by veo.")

    except subprocess.TimeoutExpired:
        print(f"  ✗ TIMEOUT: Analysis stopped after {TIMEOUT_SECONDS}s.")
        # Cleaning up a possible partial file
        if os.path.exists("results.json"):
            os.remove("results.json")
            
    except subprocess.CalledProcessError as e:
        print(f"  ✗ VEO ERROR: Process returned code {e.returncode}")
        
    except Exception as e:
        print(f"  ✗ UNEXPECTED ERROR: {e}")

print("\n--- All analyses are complete ---")